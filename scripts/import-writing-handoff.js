#!/usr/bin/env node
/**
 * Apply a reviewed AI-Multimedia portfolio handoff to a local portfolio checkout.
 * Intentionally never commits, pushes, deploys, opens PRs or publishes.
 *
 * Usage: node scripts/import-writing-handoff.js --input /path/to/handoff.json
 *        node scripts/import-writing-handoff.js --input /path/to/handoff.json --apply
 */
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const FORMAT = "echo-writing-portfolio-handoff/v1";
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const CATEGORIES = new Set([
  "reflection",
  "essay",
  "tech",
  "creative",
  "achievement"
]);
const ALLOWED_ENTRY_FIELDS = new Set([
  "id",
  "slug",
  "publishedDate",
  "title",
  "excerpt",
  "category",
  "tags",
  "readingTime",
  "featured",
  "cover",
  "source"
]);
const ROOT = path.resolve(__dirname, "..");
const INDEX_PATH = path.join(ROOT, "apps/web/public/content/index.json");
const ARTICLES_PATH = path.join(ROOT, "apps/web/public/content/articles");

function fail(message) {
  throw new Error(message);
}
function isText(value) {
  return typeof value === "string" && value.trim().length > 0;
}
function validDate(value) {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value))
    return false;
  const date = new Date(`${value}T00:00:00Z`);
  return (
    !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value
  );
}
function parseJson(text) {
  // JSON.parse accepts duplicate keys. This handoff is generated by a trusted
  // producer, but extra-field checks and end-to-end preview are still mandatory.
  return JSON.parse(text);
}
function validateEntry(entry) {
  if (!entry || typeof entry !== "object" || Array.isArray(entry))
    fail("entry must be an object");
  for (const field of Object.keys(entry)) {
    if (!ALLOWED_ENTRY_FIELDS.has(field))
      fail(`Unexpected public entry field: ${field}`);
  }
  const slug = entry.slug ?? entry.id;
  if (
    typeof entry.id !== "string" ||
    !SLUG.test(entry.id) ||
    typeof slug !== "string" ||
    !SLUG.test(slug)
  ) {
    fail("entry.id / entry.slug must be lowercase hyphenated slugs");
  }
  if (!validDate(entry.publishedDate))
    fail("entry.publishedDate must be a valid YYYY-MM-DD");
  for (const key of ["title", "excerpt"]) {
    const value = entry[key];
    if (
      !value ||
      typeof value !== "object" ||
      Array.isArray(value) ||
      !Object.keys(value).every(k => ["zh", "en"].includes(k)) ||
      !isText(value.zh) ||
      ("en" in value && typeof value.en !== "string")
    ) {
      fail(`entry.${key} must contain zh text (and optional en text)`);
    }
  }
  if (!CATEGORIES.has(entry.category)) fail("Unsupported writing category");
  if (!Array.isArray(entry.tags) || !entry.tags.every(isText))
    fail("entry.tags must be an array of nonempty strings");
  if (!Number.isInteger(entry.readingTime) || entry.readingTime <= 0)
    fail("Invalid readingTime");
  if (typeof entry.featured !== "boolean") fail("featured must be boolean");
  if ("cover" in entry) {
    const cover = entry.cover;
    if (!isText(cover)) fail("cover must be nonempty text");
    if (cover.startsWith("/")) {
      if (
        cover.startsWith("//") ||
        cover.split("/").some(part => part === "..")
      ) {
        fail("Unsafe local cover");
      }
      const imagePath = path.resolve(ROOT, "apps/web/public", "." + cover);
      const publicRoot = path.resolve(ROOT, "apps/web/public");
      if (
        !imagePath.startsWith(publicRoot + path.sep) ||
        !fs.existsSync(imagePath)
      ) {
        fail("Local cover must already exist in apps/web/public");
      }
    } else {
      let url;
      try {
        url = new URL(cover);
      } catch {
        fail("Invalid cover URL");
      }
      if (
        url.protocol !== "https:" ||
        url.hostname !== "img.chenchen-echo.com" ||
        url.username ||
        url.password
      )
        fail("Remote cover must use the public image domain");
    }
  }
  if ("source" in entry) {
    if (
      !entry.source ||
      typeof entry.source !== "object" ||
      Array.isArray(entry.source) ||
      Object.keys(entry.source).join(",") !== "wechat"
    ) {
      fail("source only allows a confirmed public WeChat URL");
    }
    const url = new URL(entry.source.wechat);
    if (
      url.protocol !== "https:" ||
      url.hostname !== "mp.weixin.qq.com" ||
      url.username ||
      url.password
    )
      fail("Invalid public WeChat source URL");
  }
  return {...entry, slug};
}
function validateHandoff(handoff) {
  if (
    !handoff ||
    typeof handoff !== "object" ||
    Array.isArray(handoff) ||
    Object.keys(handoff).sort().join(",") !== "body,entry,format"
  )
    fail("Invalid handoff top-level format");
  if (handoff.format !== FORMAT) fail("Unknown handoff format version");
  const entry = validateEntry(handoff.entry);
  const body = handoff.body;
  if (
    !body ||
    typeof body !== "object" ||
    Array.isArray(body) ||
    Object.keys(body).sort().join(",") !== "markdown,sha256" ||
    !isText(body.markdown) ||
    body.markdown.trim().length < 20 ||
    !/^[a-f0-9]{64}$/.test(body.sha256)
  )
    fail("Invalid handoff body");
  const digest = crypto
    .createHash("sha256")
    .update(body.markdown, "utf8")
    .digest("hex");
  if (digest !== body.sha256)
    fail("Content hash mismatch; handoff has changed since review");
  const publicData = JSON.stringify({
    entry,
    markdown: body.markdown
  }).toLowerCase();
  // Match the producer's conservative whole-domain guard (Docs, Sheets, Slides).
  if (
    /drive\.google\.com|docs\.google\.com|accounts\.google\.com/.test(publicData)
  ) {
    fail("Potential private Google Drive link in public content");
  }
  return {entry, markdown: body.markdown};
}

function preflight(handoff, index, root = ROOT) {
  const {entry, markdown} = validateHandoff(handoff);
  if (!Array.isArray(index)) fail("Portfolio index.json must be an array");
  if (index.some(item => item.id === entry.id)) {
    fail(
      `Article id already exists: ${entry.id}; never overwrite a published article implicitly`
    );
  }
  const slugs = new Set(index.map(item => item.slug || item.id));
  if (slugs.has(entry.slug)) {
    fail(`Public slug already exists: ${entry.slug}`);
  }
  const articlePath = path.join(
    root,
    "apps/web/public/content/articles",
    `${entry.id}.zh.md`
  );
  if (fs.existsSync(articlePath))
    fail("Article body already exists; overwrite refused");
  return {entry, markdown, articlePath};
}

function run(argv = process.argv.slice(2)) {
  const inputIndex = argv.indexOf("--input");
  if (inputIndex < 0 || !argv[inputIndex + 1])
    fail("Usage: --input /path/handoff.json [--apply]");
  const extra = argv.filter(
    (a, idx) => idx !== inputIndex && idx !== inputIndex + 1
  );
  if (
    !extra.every(arg => arg === "--apply") ||
    extra.filter(x => x === "--apply").length > 1
  ) {
    fail("Only --input and optional --apply are supported");
  }
  const apply = extra.includes("--apply");
  const handoff = parseJson(
    fs.readFileSync(path.resolve(argv[inputIndex + 1]), "utf8")
  );
  const index = parseJson(fs.readFileSync(INDEX_PATH, "utf8"));
  const {entry, markdown, articlePath} = preflight(handoff, index);
  console.log(
    `${apply ? "APPLY" : "DRY RUN"}: ${entry.title.zh} → /writing/${entry.slug}`
  );
  console.log(
    `New public files: ${path.relative(
      ROOT,
      articlePath
    )}, apps/web/public/content/index.json`
  );
  if (!apply) {
    console.log(
      "No files changed. Use --apply only after reviewing the source and public metadata."
    );
    return;
  }
  // Both files are local only. If any subsequent check fails, inspect the git diff
  // before retrying. This tool does not commit or trigger deployment.
  fs.writeFileSync(articlePath, markdown, {encoding: "utf8", flag: "wx"});
  try {
    fs.writeFileSync(
      INDEX_PATH,
      JSON.stringify([...index, entry], null, 2) + "\n",
      "utf8"
    );
  } catch (error) {
    fs.unlinkSync(articlePath);
    throw error;
  }
  console.log(
    "Local changes applied. Run npm run content:validate && npm run verify; review git diff and open a PR manually."
  );
}

if (require.main === module) {
  try {
    run();
  } catch (error) {
    console.error(`Import refused: ${error.message}`);
    process.exitCode = 1;
  }
}
module.exports = {validateHandoff, preflight, run};
